# ---------------------------------------------------------------------------
# Vacuum fixture
# ---------------------------------------------------------------------------


def build_vacuum_world(ref: np.ndarray, n_slices: int, r_t: float) -> np.ndarray:
    """The ``A=0`` calibration fixture: reference lattice + the prestressed N-gon.

    Every node sits at its reference position on every slice, with only the
    per-slice global N-gon offset (the prestressed-vacuum background) added to the
    carrier 2-plane.  This is exactly the seed with ``A0=0`` — the state on which
    every device MUST read null after subtracting the offset.
    """
    n_nodes, m_ambient = ref.shape
    world = np.broadcast_to(ref, (n_slices + 1, n_nodes, m_ambient)).copy()
    off_re, off_im = vacuum_offsets(n_slices, r_t)
    world[:, :, CARRIER_RE] += off_re[:, np.newaxis]
    world[:, :, CARRIER_IM] += off_im[:, np.newaxis]
    return world


