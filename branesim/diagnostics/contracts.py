_STATUS_FROM_BOOL = {True: "PASS", False: "FAIL", None: "untested"}


def build_ledger(
    results: dict[str, dict],
    calib_results: dict[str, dict],
    ctx: dict[str, Any],
) -> tuple[list[dict[str, Any]], int | None]:
    """Assemble ledger rows and the first failing emergence layer.

    Parameters
    ----------
    results : dict
        device name -> metric dict, measured on the actual run state.
    calib_results : dict
        device name -> metric dict, measured on the vacuum fixture (only for
        devices with ``calib_fixture == "vacuum"``).
    ctx : dict
        ``converged``, ``m``, ``n_t``, ``state``.

    Returns
    -------
    rows : list of dict (sorted by layer) with keys
        device, layer, layer_name, calib, falsifier, interpretable,
        calib_desc, falsifier_desc.
    first_fail_layer : int or None
        Lowest layer with any FAIL (calibration or falsifier); None if none fail.
    """
    rows: list[dict[str, Any]] = []
    for name, c in CONTRACTS.items():
        res = results.get(name, {})
        errored = "error" in res

        # --- calibration status ---
        if c.calib_fixture == "none":
            calib = "—"
        else:
            cres = calib_results.get(name)
            if cres is None or "error" in cres or c.calib_check is None:
                calib = "ERROR"
            else:
                try:
                    calib = "PASS" if c.calib_check(cres) else "FAIL"
                except Exception:
                    calib = "ERROR"

        # --- falsifier status ---
        if errored:
            falsifier = "ERROR"
        else:
            try:
                falsifier = _STATUS_FROM_BOOL.get(c.falsifier(res, ctx), "?")
            except Exception:
                falsifier = "ERROR"

        rows.append({
            "device": name,
            "layer": c.layer,
            "layer_name": c.layer_name,
            "calib": calib,
            "falsifier": falsifier,
            "calib_desc": c.calib_desc,
            "falsifier_desc": c.falsifier_desc,
        })

    fail_layers = [r["layer"] for r in rows
                   if r["calib"] == "FAIL" or r["falsifier"] == "FAIL"]
    first_fail = min(fail_layers) if fail_layers else None

    for r in rows:
        r["interpretable"] = first_fail is None or r["layer"] <= first_fail

    rows.sort(key=lambda r: (r["layer"], r["device"]))
    return rows, first_fail


def render_ledger_md(
    rows: list[dict[str, Any]],
    first_fail: int | None,
    ctx: dict[str, Any],
) -> str:
    """Render the trust ledger as the top section of report.md."""
    state = ctx.get("state", "?")
    verdict = (f"All instrumented layers interpretable (no calibration/falsifier "
               f"failure)."
               if first_fail is None else
               f"**First failing layer: L{first_fail}.** Devices above L{first_fail} "
               f"rest on a failed lower layer and are marked uninterpretable (⊘) — "
               f"fix the first ✗ before reading them.")

    lines = [
        "## Trust Ledger",
        "",
        f"State measured: **{state}**.  {verdict}",
        "",
        "| Layer | Device | Calibration (A=0 null) | Falsifier (pre-registered) | Verdict |",
        "|-------|--------|------------------------|----------------------------|---------|",
    ]
    sym = {"PASS": "✓ PASS", "FAIL": "✗ FAIL", "untested": "· untested",
           "ERROR": "! ERROR", "—": "— n/a", "?": "?"}
    for r in rows:
        if not r["interpretable"]:
            verdict_cell = "⊘ uninterpretable"
        elif r["falsifier"] == "FAIL" or r["calib"] == "FAIL":
            verdict_cell = "✗ FAIL"
        elif r["calib"] == "ERROR" or r["falsifier"] == "ERROR":
            verdict_cell = "! ERROR"
        elif r["falsifier"] == "PASS":
            verdict_cell = "✓ PASS"
        else:
            verdict_cell = "· provisional"
        lines.append(
            f"| L{r['layer']} {r['layer_name'].split(' ',1)[1] if ' ' in r['layer_name'] else ''} "
            f"| `{r['device']}` "
            f"| {sym.get(r['calib'], r['calib'])} — {r['calib_desc']} "
            f"| {sym.get(r['falsifier'], r['falsifier'])} — {r['falsifier_desc']} "
            f"| {verdict_cell} |"
        )
    lines += [
        "",
        "*Legend:* calibration runs each device on the vacuum (`A=0`) fixture in "
        "this same run and checks it reads null; the falsifier is the pre-registered "
        "pass criterion (in `branesim/diagnostics/contracts.py`). `untested` = a "
        "physics check only meaningful on a converged solved state. `⊘` = the layer "
        "below failed, so this verdict cannot be trusted yet.",
        "",
        "---",
        "",
    ]
    return "\n".join(lines)