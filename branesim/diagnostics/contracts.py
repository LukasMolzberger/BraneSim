"""Device contracts + the per-run trust ledger.

This module encodes the three single-shot-experiment disciplines as data, so the
trust ledger at the top of every ``report.md`` is generated by construction
rather than by remembering to check things by hand:

  1. **Known-answer calibration** — each device declares a fixture (here, the
     vacuum / ``A=0`` state) and a null-predicate that its output MUST satisfy
     when run on that fixture *in the same run*.  A device whose calibration
     fails this run does not get to vote on physics.  (The vacuum self-test also
     catches the prestressed-N-gon offset-subtraction bugs that LESSONS_LEARNED
     warns about: if a device forgets to subtract the offset, its vacuum output
     is non-null and calibration FAILS.)

  2. **Pre-registered falsifier** — each device declares, as a predicate living
     in *this* version-controlled file, what would count as a pass.  Moving a
     threshold to make a result pass shows up as a diff in the contract, not
     buried in the measurement: the "fixing the instrument vs. tuning to confirm"
     line made visible in git.

  3. **Layered, bottom-up analysis** — each device carries an emergence-layer
     rank.  The ledger sorts by layer and finds the first failing layer; every
     device above it is marked *uninterpretable* (it rests on a failed lower
     layer), so a human reads the run bottom-up and fixes the first ✗.

Falsifier predicates take ``(result, ctx)`` and return ``True`` (pass),
``False`` (fail), or ``None`` (untested — e.g. a physics check that is only
meaningful on a converged solved state, not on the seed).  ``ctx`` carries
``converged``, ``m``, ``n_t`` and a human-readable ``state`` string.

Design constraint (PRINCIPLES §2): read-only.  Nothing here mutates solver
state; calibration runs devices on a synthesized vacuum world into a throwaway
directory and inspects only their returned metric dicts.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any, Callable

import numpy as np

from branesim.initialization.vortex_worldtube import (
    CARRIER_RE,
    CARRIER_IM,
    vacuum_offsets,
)

# Tolerances (the version-controlled thresholds — move with intent, see the diff).
NULL_TOL: float = 1e-6        # |metric| below this on the vacuum fixture = null
ENERGY_NULL_TOL: float = 1e-8  # V_excess at the reference config
CONS_TOL: float = 1e-2        # energy-conservation max relative deviation
SPREAD_LOCALIZED: float = 1.0  # spread_ratio < this = localized (not box-filling)
U1_PURE_FRAC: float = 0.99    # pure-EM (trace) seed: U(1) energy fraction ≈ 1
BINDING_NOISE: float = 1e-3   # Δu_∥ extremum must exceed this to count as signal


# ---------------------------------------------------------------------------
# Contract dataclass + registry
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class DeviceContract:
    """The three declarations that make a device's output trustworthy.

    Attributes
    ----------
    layer : int
        Emergence rank (1 substrate/linear → 5 soliton).  Lower layers must hold
        before higher-layer verdicts are interpretable.
    layer_name : str
        Human label for the layer.
    calib_fixture : {"vacuum", "none"}
        Which known-answer fixture calibrates this device.  ``"vacuum"`` runs the
        device on the ``A=0`` state and checks ``calib_check``.  ``"none"`` means
        no clean vacuum null exists yet (declared gap; shown as ``—``).
    calib_desc : str
        One-line description of the calibration.
    calib_check : callable(result_dict) -> bool | None
        Null-predicate on the device's output when run on the fixture.  ``None``
        iff ``calib_fixture == "none"``.
    falsifier_desc : str
        One-line description of the pre-registered pass criterion.
    falsifier : callable(result_dict, ctx) -> bool | None
        ``True`` pass / ``False`` fail / ``None`` untested-on-this-state.
    """

    layer: int
    layer_name: str
    calib_fixture: str
    calib_desc: str
    calib_check: Callable[[dict], bool] | None
    falsifier_desc: str
    falsifier: Callable[[dict, dict], bool | None]


def _num(d: dict, key: str, default: float = float("nan")) -> float:
    """Pull a numeric metric, tolerating missing/non-numeric entries."""
    v = d.get(key, default)
    try:
        return float(v)
    except (TypeError, ValueError):
        return float("nan")


